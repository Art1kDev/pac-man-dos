static void DrawCellToScreen(int r, int c)
{
    int code, g, row, p, v, cc;
    unsigned long off;
    if (r < 0 || r > 22 || c < 0 || c > 39) return;
    code = maze[r * 40 + c];
    g = code & 0x7F;
    off = (unsigned long)(MAZE_TOP + r * 8) * 320UL + (unsigned)(c * 8);
    for (row = 0; row < 8; row++) {
        if (g <= 114) {
            for (p = 0; p < 4; p++) {
                v = (pacchr[g][row] >> (6 - 2 * p)) & 3;
                if (code & 0x80)
                    cc = v ? C_RED : C_BLACK;
                else if (g >= 58 && g <= 76)
                    cc = FruitPix(v);
                else
                    cc = c2c[v];
                VSet(off, (byte)cc);
                VSet(off + 1, (byte)cc);
                off += 2;
            }
        } else
            off += 8;
        off += 312;
    }
}

