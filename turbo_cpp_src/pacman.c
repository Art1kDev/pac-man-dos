static int AsciiGlyph(int ch)
{
    if (ch >= '0' && ch <= '9') return 0x10 + ch - '0';
    if (ch >= 'A' && ch <= 'Z') return 0x21 + ch - 'A';
    if (ch >= 'a' && ch <= 'z') return 0x21 + ch - 'a';
    if (ch == '.') return 0x0C;
    if (ch == '-') return 0x0B;
    if (ch == '/') return 0x0A;
    if (ch == ':') return 0x0D;
    return 0;
}

static void SplashGlyph(int px, int py, int ch, int col, int xsc, int ysc)
{
    int row, j, sx, sy;
    byte b;
    ch = AsciiGlyph(ch);
    for (row = 0; row < 8; row++) {
        b = OsGlyph(ch, row);
        for (j = 0; j < 8; j++) {
            if ((b & (0x80 >> j)) == 0) continue;
            for (sy = 0; sy < ysc; sy++)
                for (sx = 0; sx < xsc; sx++)
                    PutPix(px + j * xsc + sx, py + row * ysc + sy, col);
        }
    }
}

static void SplashStr(int px, int py, char *s, int col, int xsc, int ysc)
{
    int i;
    for (i = 0; s[i]; i++)
        SplashGlyph(px + i * 8 * xsc, py, (unsigned char)s[i], col, xsc, ysc);
}

