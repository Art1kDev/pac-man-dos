static byte Mazhnd(int x)
{
    int idx, y;
    byte cur_vpos, cur_hpos;
    byte carry = 0;

    if (x == 4) { cur_vpos = pmvpos; cur_hpos = pmhpos; }
    else        { cur_vpos = mvpos[x]; cur_hpos = mhpos[x]; }

    idx = 9;
    while (idx >= 0 && cur_vpos != vtable[idx]) idx--;
    if (idx < 0) {
        y = 9;
        while (y >= 0 && cur_hpos != htable[y]) y--;
        if (y < 0) { temloc = 0x0C; return 0; }
        temloc = 3;
        return 0;
    }
    y = 9;
    while (y >= 0 && cur_hpos != htable[y]) y--;
    if (y < 0) {
        temloc = 0x0C;
        return 0;
    }
    temloc = htab[idx][y];
    carry = 1;

    if (x != 4) {
        temloc = (byte)(temloc & revtab[mdirt[x]]);
        if (mvpos[x] == 0x64) {
            if (mhpos[x] == 0x76 || mhpos[x] == 0x82) {
                if (mstat[x] & 0x80)
                    temloc = 1;
                else {
                    temloc = (byte)(temloc & 0x0E);
                    if (temloc == 0) temloc = 1;
                }
            }
        }
    }
    return carry;
}

static void MDirct(int x)
{
    byte v, h, r;

    if (mvpos[x] == mtvps[x]) v = 0;
    else if (mvpos[x] < mtvps[x]) {
        v = (mstat[x] & 0x80) ? 1 : 2;
    } else {
        v = (mstat[x] & 0x80) ? 2 : 1;
    }
    mvdir[x] = v;

    if (mhpos[x] == mthps[x]) h = 0;
    else if (mhpos[x] < mthps[x]) {
        h = (mstat[x] & 0x80) ? 4 : 8;
    } else {
        h = (mstat[x] & 0x80) ? 8 : 4;
    }
    mhdir[x] = h;

    if (v != 0 && (v & temloc)) {
        if (h != 0 && (h & temloc)) {
            r = (byte)(rand() & 0xFF);
            if (r & 0x80) {
                if (h) mdirt[x] = h;
                else if (v) mdirt[x] = v;
            } else {
                if (v) mdirt[x] = v;
                else if (h) mdirt[x] = h;
            }
            return;
        }
        mdirt[x] = v;
        return;
    }
    if (h != 0 && (h & temloc)) {
        mdirt[x] = h;
        return;
    }
    r = (byte)(rand() & 0xFF);
    r = (byte)(r & temloc);
    if (r) {
        if (r & 1) mdirt[x] = 1;
        else if (r & 2) mdirt[x] = 2;
        else if (r & 4) mdirt[x] = 4;
        else mdirt[x] = 8;
    } else {
        if (temloc & 1) mdirt[x] = 1;
        else if (temloc & 2) mdirt[x] = 2;
        else if (temloc & 4) mdirt[x] = 4;
        else mdirt[x] = 8;
    }
}

