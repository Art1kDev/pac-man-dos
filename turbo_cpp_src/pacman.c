static void ImRenderStrip(void)
{
    int r, c, idx, ch, g, row, p, v, x0, y0, cc;
    for (r = 0; r < 3; r++) {
        for (c = 0; c < 40; c++) {
            idx = r * 40 + ((imscroll + c) % 40);
            ch = imstrip[idx];
            g = ch & 0x3F;
            x0 = c * 8;
            y0 = 96 + r * 8;
            for (row = 0; row < 8; row++) {
                if (g <= 63) {
                    for (p = 0; p < 4; p++) {
                        v = (ichars[g * 8 + row] >> (6 - 2 * p)) & 3;
                        switch (ch >> 6) {
                            case 0:
                                if (v == 0) cc = C_BLACK;
                                else if (v == 1) cc = C_BLUE;
                                else if (v == 2) cc = C_CYAN;
                                else cc = C_YELLOW;
                                break;
                            case 1: cc = v ? C_BLUE : C_BLACK; break;
                            case 2: cc = v ? C_CYAN : C_BLACK; break;
                            default: cc = v ? C_YELLOW : C_BLACK; break;
                        }
                        PutPix(x0 + p * 2,     y0 + row, cc);
                        PutPix(x0 + p * 2 + 1, y0 + row, cc);
                    }
                }
            }
        }
    }
}

